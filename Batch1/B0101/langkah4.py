# Konversi String ke Integer
str_angka = "100"
int_angka = int(str_angka)
print("Hasil Penjumlahan (100 + 50) : ", int_angka + 50)

# Konversi Float ke Integer (Angka di belakang koma dihilangkan)
ipk_float = 3.75
ipk_int = int(ipk_float)
print("Float ke Integer : ", ipk_int)

# Konversi Integer ke String
tahun = 2026
pesan = "Tahun saat ini : " + str(tahun)
print(pesan)

# Konversi List ke Set (menghapus elemen duplikat)
daftar_buah = ["Apel", "Jeruk", "Apel", "Pisang", "Jeruk"]
buah_unik = set(daftar_buah)
print(buah_unik)